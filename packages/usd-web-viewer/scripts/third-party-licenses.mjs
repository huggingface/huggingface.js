// Writes THIRD_PARTY_LICENSES: every crate linked into the
// WASM module (normal dependencies for wasm32, not proc-macros or build
// scripts) with its license text. Where a crate offers MIT among
// alternatives, MIT is the one used.
// usage: node scripts/third-party-licenses.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const OUT = new URL("../THIRD_PARTY_LICENSES", import.meta.url);
const ROOT_CRATE = "usd-wasm";
const LICENSE_FILE = /^(licen[cs]e|copying|unlicense)/i;
// The openusd crates are published without the repository's LICENSE, so its MIT text is kept here.
const VENDORED = { openusd: "openusd", "openusd-schemas": "openusd" };
const FILE_FOR = {
	MIT: /mit/i,
	"Apache-2.0": /apache|copying/i,
	Zlib: /zlib/i,
	"Unicode-3.0": /unicode/i,
	"BSD-2-Clause": /bsd/i,
	Unlicense: /unlicense/i,
};

const metadata = JSON.parse(
	execFileSync(
		"cargo",
		[
			"metadata",
			"--format-version",
			"1",
			"--locked",
			"--filter-platform",
			"wasm32-unknown-unknown",
			"--manifest-path",
			new URL("../Cargo.toml", import.meta.url).pathname,
		],
		{ maxBuffer: 1 << 28 },
	),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const isProcMacro = (p) => p.targets.some((t) => t.kind.includes("proc-macro"));

const root = metadata.packages.find((p) => p.name === ROOT_CRATE).id;
const linked = new Set();
const stack = [root];
while (stack.length) {
	const id = stack.pop();
	if (linked.has(id)) continue;
	linked.add(id);
	for (const dep of nodes.get(id).deps) {
		if (dep.dep_kinds.some((k) => k.kind === null) && !isProcMacro(packages.get(dep.pkg))) stack.push(dep.pkg);
	}
}
linked.delete(root);

/** The licenses used: one per AND clause, MIT where a clause offers it. */
function chosen(expression) {
	return expression
		.replace(/[()]/g, "")
		.split(/\s+AND\s+/)
		.map((clause) => {
			const options = clause.split(/\s+OR\s+/).map((s) => s.trim());
			return options.includes("MIT") ? "MIT" : options[0];
		});
}

/** License files next to the manifest, at the root of a git checkout holding it, or vendored in scripts/licenses. */
function licenseFiles(p) {
	if (VENDORED[p.name]) {
		const dir = new URL(`licenses/${VENDORED[p.name]}/`, import.meta.url).pathname;
		return fs.readdirSync(dir).map((f) => path.join(dir, f));
	}
	for (let dir = path.dirname(p.manifest_path); dir !== path.dirname(dir); dir = path.dirname(dir)) {
		const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile());
		if (files.length) return files.map((f) => path.join(dir, f));
		if (fs.existsSync(path.join(dir, ".git"))) break;
	}
	return [];
}

const crates = [...linked]
	.map((id) => packages.get(id))
	.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const entries = crates.map((p) => {
	const licenses = chosen(p.license);
	const files = licenseFiles(p);
	const picked =
		files.length === 1 ? files : files.filter((f) => licenses.some((l) => FILE_FOR[l]?.test(path.basename(f))));
	if (!picked.length)
		throw new Error(
			`no license text for ${p.name} ${p.version} (${p.license}) among ${files.join(", ") || "no files"}`,
		);
	return { p, licenses, texts: picked.map((f) => [path.basename(f), fs.readFileSync(f, "utf8").trim()]) };
});

const RULE = "=".repeat(80);
const out = [
	"Third-party software linked into the WebAssembly module (wasm/usd_wasm_bg.wasm).",
	"Generated by scripts/third-party-licenses.mjs from Cargo.lock.",
	"",
	...entries.map(
		({ p, licenses }) =>
			`${p.name} ${p.version}: ${p.license}${licenses.join(" AND ") === p.license ? "" : `, used under ${licenses.join(" AND ")}`}${p.repository ? ` (${p.repository})` : ""}`,
	),
	...entries.flatMap(({ p, texts }) =>
		texts.flatMap(([name, text]) => ["", RULE, `${p.name} ${p.version}: ${name}`, RULE, "", text]),
	),
	"",
].join("\n");

fs.writeFileSync(OUT, out);
console.log(`${entries.length} crates -> ${OUT.pathname}`);
