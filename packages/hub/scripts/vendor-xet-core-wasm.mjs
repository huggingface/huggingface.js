#!/usr/bin/env node

import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [pkgDirectoryArgument, xetCoreCommit] = process.argv.slice(2);
if (!pkgDirectoryArgument || !xetCoreCommit) {
	throw new Error("Usage: vendor-xet-core-wasm.mjs <hf_xet_thin_wasm pkg directory> <xet-core commit>");
}
if (!/^[0-9a-f]{40}$/.test(xetCoreCommit)) {
	throw new Error(`Expected a full 40-character xet-core commit hash, received: ${xetCoreCommit}`);
}

const pkgDirectory = resolve(pkgDirectoryArgument);
const vendorDirectory = fileURLToPath(new URL("../src/vendor/xet-chunk", import.meta.url));
await mkdir(vendorDirectory, { recursive: true });

const wasm = await readFile(resolve(pkgDirectory, "hf_xet_thin_wasm_bg.wasm"));
const wasmBase64 = wasm
	.toString("base64")
	.match(/.{1,100}/g)
	.join("\n");
const wasmSha256 = createHash("sha256").update(wasm).digest("hex");

const base64Module = `// Generated by vendor-xet-core-wasm.mjs
// Repository: https://github.com/huggingface/xet-core.git
// Package: hf_xet_thin_wasm
// xet-core commit: ${xetCoreCommit}

export const XET_CORE_COMMIT = "${xetCoreCommit}";
export const XET_CORE_WASM_SHA256 = "${wasmSha256}";

const wasmBase64 = \`
${wasmBase64}
\`
	.trim()
	.replaceAll("\\n", "");

const wasmBinaryString = atob(wasmBase64);
export const wasmBinary = Uint8Array.from(wasmBinaryString, (character) => character.charCodeAt(0));
`;

await Promise.all([
	writeFile(resolve(vendorDirectory, "chunker_wasm_bg.wasm.base64.ts"), base64Module),
	copyFile(resolve(pkgDirectory, "hf_xet_thin_wasm.js"), resolve(vendorDirectory, "chunker_wasm_bg.js")),
	copyFile(resolve(pkgDirectory, "hf_xet_thin_wasm.d.ts"), resolve(vendorDirectory, "chunker_wasm_bg.d.ts")),
]);
